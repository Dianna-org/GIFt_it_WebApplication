export const ALL_FONTS = FONT_GROUPS.flatMap((g) => g.fonts);
const byFamily = new Map(ALL_FONTS.map((f) => [f.family, f]));

/** Ask the browser for a font (bold and italic too); `then` runs once it is there (the card is redrawn). */
export function loadFont(family, then) {
  const f = byFamily.get(family);
  const name = f?.load || (/^"([^"]+)"/.exec(family || '') || [])[1];
  if (!name || typeof document === 'undefined' || !document.fonts) return;
  Promise.all(['400', '700', 'italic 400'].map((w) => document.fonts.load(`${w} 40px "${name}"`).catch(() => null)))
    .then(() => then && then());
}
